#!/usr/bin/env python3
"""Each interop input fixture says where it comes from.

A converter test reads files that sit beside the code: an SVG, an HTML capture,
a DOCX, an xlsx. `ambre-spec-interop.md section 1.4` states where such a file
may come from, and this gate holds the half a script can read. An input file is
any file under a directory named `fixtures` inside `crates/`, except an
`.expected` file and a generator script a provenance line names. The gate fails
on each of these:

* an input file with no provenance line, or with more than one
  (`INTEROP-016`);
* a provenance line that names no file (`INTEROP-017`);
* a file of a fixture directory over the cap of `ambre-spec-budgets.md
  section 7` (`INTEROP-018`), the figure read from that row;
* a copied file whose line lacks an `https` repository, a full commit hash, an
  upstream path or a copyright holder (`INTEROP-019`);
* a copied file under a licence outside `LICENCES`, a repository with no
  licence text under `fixtures/licences/`, or a licence text no line names
  (`INTEROP-020`);
* a file named after a bug report, by its own name or its upstream name
  (`INTEROP-021`);
* an input file with no oracle: no `.expected` beside it, and no test source of
  its crate or generator script of its line that names it (`INTEROP-022`);
* an `.expected` file with no input beside it (`INTEROP-023`);
* a generated file whose script is missing or does not name it
  (`INTEROP-024`).

Whether a file is a real document, and whether the licence a line names is the
one upstream carries, stay a review (`INTEROP-025`, `INTEROP-026`): the gate
reads names and sizes, never what a file says, and it reads no network.

Run: `just fixture-provenance`. It writes nothing.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parent.parent
THIRD_PARTY = "fixtures/THIRD_PARTY.md"
AUTHORED = "fixtures/AUTHORED.md"
LICENCES = "fixtures/licences"
BUDGETS = "specs/1-Foundations/ambre-spec-budgets.md"
CAP_ROW = "Interop input fixture"

# The licences whose files an AGPL-3.0 repository may carry and ship in its
# tests. `GPL-2.0-only` is absent on purpose: it cannot combine with the AGPL.
ALLOWED_LICENCES = frozenset({
    "0BSD", "AGPL-3.0-or-later", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause",
    "CC-BY-4.0", "CC0-1.0", "GPL-2.0-or-later", "GPL-3.0-or-later", "ISC",
    "LGPL-2.1-or-later", "LGPL-3.0-or-later", "MIT", "MPL-2.0", "Unlicense",
    "Zlib",
})

COMMIT = re.compile(r"^[0-9a-f]{40}$")
REPOSITORY = re.compile(r"^https://[A-Za-z0-9.-]+(/[A-Za-z0-9._-]+)+$")
GENERATED = re.compile(r"^generated by `([^`]+)`$")
HAND_WRITTEN = "hand-written"
# A tracker name, then a number: `tdf123456`, `bug-1234`, `issue_987`, `gh-1024`,
# `i54321`. Or a bare number of five digits or more, as a tracker names a file.
BUG_NAME = re.compile(
    r"(?:^|[^a-z])(?:bugs?|issues?|tickets?|tdf|fdo|ooo|i|gh|pr|rhbz|bz|bsc|boo|lp|cve)"
    r"[-_ #]?\d{3,}"
    r"|(?:^|\D)\d{5,}(?:\D|$)",
    re.IGNORECASE,
)
CAP = re.compile(r"^(\d+) KiB\b")
CELL = re.compile(r"^`([^`]*)`$")


@dataclass(frozen=True)
class Line:
    """One provenance row: its register, its line number and its cells."""

    register: str
    number: int
    cells: tuple[str, ...]

    @property
    def path(self) -> str:
        return unquote(self.cells[0])

    @property
    def where(self) -> str:
        return f"{self.register}:{self.number}"


@dataclass(frozen=True)
class Tree:
    """What the gate reads from disk, so a test can plant it whole."""

    files: dict[str, int]  # every fixture-directory file, by path, with its size
    sources: dict[str, str]  # every `.rs` file of a crate holding a fixture, by path
    scripts: dict[str, str]  # each generator script a line names, by path, if it exists
    licences: tuple[str, ...]  # the file names under `fixtures/licences/`


def unquote(cell: str) -> str:
    """A cell without the backticks around it."""
    match = CELL.match(cell.strip())
    return match.group(1) if match else cell.strip()


def rows(register: str, text: str, width: int) -> tuple[list[Line], list[str]]:
    """The rows of one register's table, and a breach per row of the wrong width."""
    out, errors = [], []
    for number, raw in enumerate(text.splitlines(), 1):
        if not raw.startswith("| `"):
            continue
        cells = tuple(c.strip() for c in raw.strip().strip("|").split("|"))
        if len(cells) != width:
            errors.append(f"{register}:{number}: {len(cells)} cells, the table has {width}")
            continue
        out.append(Line(register, number, cells))
    return out, errors


def cap_octets(budgets: str) -> int | None:
    """The per-file cap in octets, read from its row of the budget register."""
    for raw in budgets.splitlines():
        cells = [c.strip() for c in raw.strip().strip("|").split("|")]
        if len(cells) >= 2 and cells[0] == CAP_ROW:
            match = CAP.match(cells[1])
            return int(match.group(1)) * 1024 if match else None
    return None


def crate_of(path: str) -> str:
    """The crate directory a fixture path sits in: `crates/<name>`."""
    return "/".join(PurePosixPath(path).parts[:2])


def is_expected(path: str) -> bool:
    return path.endswith(".expected")


def generator(line: Line) -> str | None:
    """The script an authored line names, if its origin is generated."""
    match = GENERATED.match(line.cells[1])
    return match.group(1) if match else None


def breaches(third: str, authored: str, budgets: str, tree: Tree) -> tuple[list[str], int]:
    """Every breach of the two registers against the tree, and the input count."""
    copied, errors = rows(THIRD_PARTY, third, 6)
    own, more = rows(AUTHORED, authored, 3)
    errors += more
    lines = [*copied, *own]
    scripts = {s for s in (generator(line) for line in own) if s}

    cap = cap_octets(budgets)
    if cap is None:
        errors.append(f"{BUDGETS}: no `{CAP_ROW}` row with a figure in KiB")
    for path, size in sorted(tree.files.items()):
        if cap is not None and size > cap:
            errors.append(f"{path}: {size} octets, over the cap of {cap} (`{CAP_ROW}`, {BUDGETS})")

    inputs = sorted(p for p in tree.files if not is_expected(p) and p not in scripts)
    by_path: dict[str, list[Line]] = {}
    for line in lines:
        by_path.setdefault(line.path, []).append(line)
    for path in inputs:
        found = by_path.get(path, [])
        if not found:
            errors.append(f"{path}: no provenance line in {THIRD_PARTY} or {AUTHORED}")
        elif len(found) > 1:
            where = ", ".join(line.where for line in found)
            errors.append(f"{path}: {len(found)} provenance lines ({where}), one is the rule")
    for line in lines:
        if line.path not in tree.files:
            errors.append(f"{line.where}: `{line.path}` names no file")
        elif line.path in scripts or is_expected(line.path):
            errors.append(f"{line.where}: `{line.path}` is no input file")

    errors += copied_breaches(copied, tree)
    errors += authored_breaches(own, tree)
    errors += name_breaches(inputs, copied)
    errors += oracle_breaches(inputs, own, tree)
    return errors, len(inputs)


def copied_breaches(copied: list[Line], tree: Tree) -> list[str]:
    """The cells of each copied line, and the licence texts beside them."""
    errors = []
    names = set()
    for line in copied:
        repository, commit, upstream, licence, holder = (unquote(c) for c in line.cells[1:])
        if not REPOSITORY.match(repository):
            errors.append(f"{line.where}: `{repository}` is no https repository")
        else:
            names.add(repository.rstrip("/").rsplit("/", 1)[-1].lower())
        if not COMMIT.match(commit):
            errors.append(f"{line.where}: `{commit}` is no full commit hash")
        if not upstream:
            errors.append(f"{line.where}: no upstream path")
        if licence not in ALLOWED_LICENCES:
            errors.append(f"{line.where}: licence `{licence}` is not one the repository may carry")
        if not holder:
            errors.append(f"{line.where}: no copyright holder")
    for name in sorted(names):
        if f"{name}.txt" not in tree.licences:
            errors.append(f"{LICENCES}/{name}.txt: missing, and {THIRD_PARTY} copies from `{name}`")
    for text in tree.licences:
        stem = text.removesuffix(".txt")
        if not any(stem == n or stem.startswith(f"{n}-") for n in names):
            errors.append(f"{LICENCES}/{text}: no line of {THIRD_PARTY} copies from its repository")
    return errors


def authored_breaches(own: list[Line], tree: Tree) -> list[str]:
    """The origin of each authored line, and the script a generated one names."""
    errors = []
    for line in own:
        origin = line.cells[1]
        script = generator(line)
        if script is None and origin != HAND_WRITTEN:
            errors.append(f"{line.where}: origin `{origin}` is neither `{HAND_WRITTEN}` nor `generated by` a script")
        if not line.cells[2]:
            errors.append(f"{line.where}: `Holds` is empty")
        if script is None:
            continue
        text = tree.scripts.get(script)
        if text is None:
            errors.append(f"{line.where}: the script `{script}` does not exist")
        elif PurePosixPath(line.path).name not in text:
            errors.append(f"{line.where}: the script `{script}` does not name `{PurePosixPath(line.path).name}`")
    return errors


def name_breaches(inputs: list[str], copied: list[Line]) -> list[str]:
    """A file named after a bug report, here or upstream."""
    errors = []
    for path in inputs:
        if BUG_NAME.search(PurePosixPath(path).stem):
            errors.append(f"{path}: the name reads as a bug report")
    for line in copied:
        upstream = PurePosixPath(unquote(line.cells[3])).stem
        if BUG_NAME.search(upstream):
            errors.append(f"{line.where}: the upstream name `{upstream}` reads as a bug report")
    return errors


def oracle_breaches(inputs: list[str], own: list[Line], tree: Tree) -> list[str]:
    """An input with no oracle, and an `.expected` file with no input."""
    errors = []
    expected = {p for p in tree.files if is_expected(p)}
    readers: dict[str, list[str]] = {}
    for line in own:
        script = generator(line)
        if script and script in tree.scripts:
            readers.setdefault(crate_of(line.path), []).append(tree.scripts[script])
    for path in inputs:
        pure = PurePosixPath(path)
        beside = {str(pure.with_suffix(".expected")), f"{path}.expected"}
        if beside & expected:
            continue
        texts = [t for p, t in tree.sources.items() if crate_of(p) == crate_of(path)]
        texts += readers.get(crate_of(path), [])
        if not any(pure.name in t for t in texts):
            errors.append(f"{path}: no oracle, no `.expected` beside it and no test or script names it")
    stems = {str(PurePosixPath(p).with_suffix("")) for p in inputs}
    for path in sorted(expected):
        base = path[: -len(".expected")]
        if base not in inputs and base not in stems:
            errors.append(f"{path}: no input file beside it")
    return errors


def scan(third: str, authored: str) -> Tree:
    """Read the fixture directories, the crate sources and the named scripts."""
    files = {}
    crates = set()
    for directory in sorted((ROOT / "crates").glob("**/fixtures")):
        if not directory.is_dir() or "target" in directory.relative_to(ROOT).parts:
            continue
        for file in directory.rglob("*"):
            if file.is_file():
                path = file.relative_to(ROOT).as_posix()
                files[path] = file.stat().st_size
                crates.add(crate_of(path))
    sources = {}
    for crate in sorted(crates):
        for file in (ROOT / crate).rglob("*.rs"):
            sources[file.relative_to(ROOT).as_posix()] = file.read_text(encoding="utf-8")
    scripts = {}
    for line in rows(AUTHORED, authored, 3)[0]:
        script = generator(line)
        if script and (ROOT / script).is_file():
            scripts[script] = (ROOT / script).read_text(encoding="utf-8")
    licences = tuple(sorted(p.name for p in (ROOT / LICENCES).glob("*") if p.is_file()))
    return Tree(files, sources, scripts, licences)


def read(path: str) -> str:
    """The text of one file of the repository."""
    return (ROOT / path).read_text(encoding="utf-8")


def main() -> int:
    third, authored = read(THIRD_PARTY), read(AUTHORED)
    errors, count = breaches(third, authored, read(BUDGETS), scan(third, authored))
    if errors:
        print("\n".join(errors), file=sys.stderr)
        print(f"fixture provenance: {len(errors)} breach(es) over {count} input files", file=sys.stderr)
        return 1
    print(f"fixture provenance: {count} input files, each with one provenance line, under the cap")
    return 0


if __name__ == "__main__":
    sys.exit(main())
