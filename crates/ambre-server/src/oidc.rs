use openidconnect::core::{
    CoreAuthenticationFlow, CoreClient, CoreIdTokenClaims, CoreProviderMetadata,
};
use openidconnect::{
    AuthorizationCode, ClientId, ClientSecret, CsrfToken, EndpointMaybeSet, EndpointNotSet,
    EndpointSet, IssuerUrl, Nonce, PkceCodeChallenge, PkceCodeVerifier, RedirectUrl, Scope,
    TokenResponse,
};
use std::collections::HashMap;
use std::sync::Arc;

use crate::error::AppError;

/// Concrete OIDC client type with all endpoint URLs set from provider discovery.
///
/// `EndpointSet` for `HasAuthUrl` allows `authorize_url()`. `EndpointMaybeSet`
/// for `HasTokenUrl` and `HasUserInfoUrl` covers providers that include token
/// and userinfo endpoints in their .well-known metadata (most do).
pub type OidcClient = CoreClient<
    EndpointSet,
    EndpointNotSet,
    EndpointNotSet,
    EndpointNotSet,
    EndpointMaybeSet,
    EndpointMaybeSet,
>;

/// Per-provider OIDC state: the configured client and its redirect URI.
///
/// The redirect URI is stored separately from the client so the same
/// `OidcClient` can be used by `login_url` and `exchange_code` without
/// baking the URI into the typestate at construction time.
pub struct OidcProviderState {
    pub client: OidcClient,
    pub redirect_uri: RedirectUrl,
}

/// Map of OIDC provider name ("google", "github", …) to its state.
///
/// Wrapped in `Arc` so every Axum handler can reference the same
/// discovered clients without cloning the entire map.
pub type OidcClients = Arc<HashMap<String, OidcProviderState>>;

/// Returned by `GET /auth/{provider}/login`.
///
/// The client redirects the browser to `url` which begins the
/// authorization code flow at the OIDC provider.
#[derive(serde::Serialize)]
pub struct LoginResponse {
    pub url: String,
    pub state: String,
}

/// Received by `POST /auth/{provider}/callback`.
///
/// The client sends the authorization `code` and the `state` (CSRF token)
/// returned by the login endpoint. The server validates the state against
/// Redis, exchanges the code for tokens, and creates a session.
#[derive(serde::Deserialize)]
pub struct CallbackRequest {
    pub code: String,
    pub state: String,
}

/// Returned by `POST /auth/{provider}/callback` after successful authentication.
#[derive(serde::Serialize)]
pub struct CallbackResponse {
    pub user_id: String,
    pub email: String,
    pub display_name: String,
    /// True when the user row was just created (no master key yet).
    /// The client should prompt the user to set up their master key.
    pub is_new_user: bool,
    /// Access JWT, kept in client memory and sent as `Authorization: Bearer`.
    pub access_token: String,
    /// Opaque refresh token, exchanged at `/auth/refresh` for a new access JWT.
    pub refresh_token: String,
    /// Access-token lifetime in seconds, so the client can schedule a refresh.
    pub access_expires_in: u64,
}

/// Transient OIDC authorization state stored in Redis (TTL 10 min).
///
/// The PKCE verifier and nonce are generated by `login_url` and must
/// be presented again during token exchange to prevent authorization
/// code interception.
pub struct OidcAuthState {
    pub pkce_verifier_secret: String,
    pub nonce: Nonce,
}

/// Discovers Google's OIDC provider metadata and initializes an `OidcClient`.
///
/// The resulting `OidcClients` map is stored in `AppState` and used by
/// the `/auth/{provider}/login` and `/auth/{provider}/callback` routes.
pub async fn init_oidc_clients(
    google_client_id: &str,
    google_client_secret: &str,
    google_redirect_uri: &str,
) -> Result<OidcClients, AppError> {
    let http_client = reqwest::Client::new();

    let google_issuer = IssuerUrl::new("https://accounts.google.com".to_string())
        .map_err(|e| AppError::Oidc(format!("invalid google issuer URL: {e}")))?;

    let provider_metadata = CoreProviderMetadata::discover_async(google_issuer, &http_client)
        .await
        .map_err(|e| AppError::Oidc(format!("google discovery failed: {e}")))?;

    let redirect_uri = RedirectUrl::new(google_redirect_uri.to_string())
        .map_err(|e| AppError::Oidc(format!("invalid redirect URI: {e}")))?;

    let client = OidcClient::from_provider_metadata(
        provider_metadata,
        ClientId::new(google_client_id.to_string()),
        Some(ClientSecret::new(google_client_secret.to_string())),
    );

    let mut map = HashMap::new();
    map.insert(
        "google".to_string(),
        OidcProviderState {
            client,
            redirect_uri,
        },
    );

    Ok(Arc::new(map))
}

/// Generates an OIDC authorization URL with PKCE challenge, CSRF token, and nonce.
///
/// Returns the URL the client must redirect to and the `OidcAuthState` that
/// must be stored in Redis (keyed by the CSRF token) so the callback can
/// validate the PKCE verifier and nonce.
pub async fn login_url(
    state: &OidcProviderState,
) -> Result<(LoginResponse, OidcAuthState), AppError> {
    let (pkce_challenge, pkce_verifier) = PkceCodeChallenge::new_random_sha256();

    let client_with_redirect = state
        .client
        .clone()
        .set_redirect_uri(state.redirect_uri.clone());

    let (auth_url, csrf_state, nonce) = client_with_redirect
        .authorize_url(
            CoreAuthenticationFlow::AuthorizationCode,
            CsrfToken::new_random,
            Nonce::new_random,
        )
        .add_scope(Scope::new("openid".to_string()))
        .add_scope(Scope::new("email".to_string()))
        .add_scope(Scope::new("profile".to_string()))
        .set_pkce_challenge(pkce_challenge)
        .url();

    let csrf_secret = csrf_state.secret().clone();
    let verifier_secret = pkce_verifier.secret().clone();

    let oidc_state = OidcAuthState {
        pkce_verifier_secret: verifier_secret,
        nonce,
    };

    Ok((
        LoginResponse {
            url: auth_url.to_string(),
            state: csrf_secret,
        },
        oidc_state,
    ))
}

/// Exchanges an authorization code for tokens, validates the ID token, and returns the claims.
///
/// Uses the PKCE verifier and nonce from the `OidcAuthState` (retrieved from Redis)
/// to prevent code interception. The ID token is verified against the provider's JWKS keys.
pub async fn exchange_code(
    provider: &OidcProviderState,
    code: String,
    stored_state: &OidcAuthState,
) -> Result<CoreIdTokenClaims, AppError> {
    let auth_code = AuthorizationCode::new(code);
    let pkce_verifier = PkceCodeVerifier::new(stored_state.pkce_verifier_secret.clone());

    let http_client = reqwest::Client::new();
    let client_with_redirect = provider
        .client
        .clone()
        .set_redirect_uri(provider.redirect_uri.clone());

    let exchange_client = client_with_redirect.clone();
    let exchange_req = exchange_client
        .exchange_code(auth_code)
        .map_err(|e| AppError::Oidc(format!("exchange_code setup failed: {e}")))?;

    let token_response = exchange_req
        .set_pkce_verifier(pkce_verifier)
        .request_async(&http_client)
        .await
        .map_err(|e| AppError::Oidc(format!("token exchange failed: {e}")))?;

    let id_token = token_response
        .id_token()
        .ok_or_else(|| AppError::Oidc("no id_token in response".into()))?;

    let claims = id_token
        .clone()
        .into_claims(
            &client_with_redirect.id_token_verifier(),
            &stored_state.nonce,
        )
        .map_err(|e| AppError::Oidc(format!("id token verification failed: {e}")))?;

    Ok(claims)
}
