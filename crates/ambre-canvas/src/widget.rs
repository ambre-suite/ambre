// ambre-canvas/src/widget.rs
// ============================================================================
// Widget trait -- the contract every UI component implements.
//
// Passes are strictly separated: each method has a single responsibility.
// Widgets never mutate framework state during dispatch -- they return
// EventResponse, which the framework applies after the dispatch cycle.
// ============================================================================

use ambre_draw::DrawSurface;
use kurbo::{Rect, Size};
use smallvec::SmallVec;

use crate::constraints::BoxConstraints;
use crate::context::{LayoutCtx, PaintCtx};
use crate::event::{EventResponse, KeyEvent, PointerEvent};

/// Stable widget identifier. Generated by slotmap -- invalid after removal.
pub type WidgetId = slotmap::DefaultKey;

/// The core UI component contract.
///
/// All coordinates are in logical pixels (dp). The origin is top-left, Y down.
pub trait Widget: 'static {
    // -- Events ---------------------------------------------------------------

    /// Pointer event (mouse/touch/stylus). Called only if the pointer is within
    /// the widget bounds (pre-filtered by WidgetPod).
    fn on_pointer_event(&mut self, event: &PointerEvent, bounds: Rect) -> EventResponse;

    /// Keyboard event. Called only on the widget that currently has focus.
    fn on_key_event(&mut self, event: &KeyEvent) -> EventResponse;

    /// Animation frame. Called every frame if `animated()` returns true.
    /// Returns true if the widget needs repainting.
    #[allow(unused_variables)]
    fn on_anim_frame(&mut self, ts_ms: f64) -> bool {
        false
    }

    // -- Layout ---------------------------------------------------------------

    /// Compute the widget size and position its children.
    /// Returns the effective Size (may differ from bc.max for Hug sizing).
    fn layout(&mut self, ctx: &mut LayoutCtx, bc: BoxConstraints) -> Size;

    // -- Rendering ------------------------------------------------------------

    /// Paint the widget into `surface`. The widget knows its absolute position
    /// via `bounds` (set by WidgetPod after layout). Zero allocation in steady
    /// state.
    fn paint(&self, ctx: &PaintCtx, surface: &mut dyn DrawSurface, bounds: Rect);

    // -- Accessibility --------------------------------------------------------

    /// Fill the AccessKit node for this widget. Called only when dirty_a11y.
    fn accessibility(&self, node: &mut accesskit::Node);

    /// AccessKit role of this widget.
    fn accessibility_role(&self) -> accesskit::Role;

    // -- Tree navigation ------------------------------------------------------

    /// IDs of direct children. Used for hit-testing, Tab order, AccessKit tree.
    fn children(&self) -> SmallVec<[WidgetId; 4]> {
        SmallVec::new()
    }

    // -- Metadata -------------------------------------------------------------

    /// Whether this widget can receive keyboard focus (Tab / Shift+Tab).
    fn focusable(&self) -> bool {
        false
    }

    /// Whether this widget animates (on_anim_frame called every frame).
    fn animated(&self) -> bool {
        false
    }
}
