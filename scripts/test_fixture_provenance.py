#!/usr/bin/env python3
"""What `fixture_provenance.py` refuses, and what it lets through.

Each test plants two registers, a budget row and a tree through `breaches`, and
asserts the verdict. Reading the disk is left to the run on the tree.

Run: `just test-scripts`, or `python3 -m unittest discover -s scripts`.
"""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import fixture_provenance as fp  # noqa: E402  -- the module under test

COMMIT = "57011cf6b1430785d0c47e5ad6eb76081d7c0e22"
COPIED = "crates/ambre-xlsx/tests/fixtures/up/date.xlsx"
SVG = "crates/ambre-toile/src/fixtures/rect.svg"
GENERATED = "crates/ambre-docx/tests/fixtures/lo/features.docx"
SOURCE = "crates/ambre-docx/tests/fixtures/lo/features.fodt"
SCRIPT = "crates/ambre-docx/tests/fixtures/lo/generate.sh"
BUDGETS = "| Interop input fixture | 64 KiB each, a ceiling | notes |\n"


def copied_row(path: str = COPIED, repository: str = "https://github.com/tafia/calamine",
               commit: str = COMMIT, upstream: str = "tests/date.xlsx", licence: str = "MIT",
               holder: str = "Copyright (c) 2016 Johann Tuffe") -> str:
    return f"| `{path}` | {repository} | `{commit}` | `{upstream}` | {licence} | {holder} |\n"


def authored_row(path: str, origin: str = "hand-written", holds: str = "one rectangle") -> str:
    return f"| `{path}` | {origin} | {holds} |\n"


HEADER3 = "| Path | Origin | Holds |\n|---|---|---|\n"
HEADER6 = "| Path | Repo | Commit | Upstream | Licence | Copyright |\n|---|---|---|---|---|---|\n"


def third(*rows: str) -> str:
    return HEADER6 + "".join(rows if rows else (copied_row(),))


def authored(*rows: str) -> str:
    default = (
        authored_row(SVG),
        authored_row(SOURCE, holds="a flat ODF text"),
        authored_row(GENERATED, f"generated by `{SCRIPT}`", "the export of the source"),
    )
    return HEADER3 + "".join(rows if rows else default)


def tree(files: dict[str, int] | None = None, sources: dict[str, str] | None = None,
         scripts: dict[str, str] | None = None,
         licences: tuple[str, ...] = ("calamine.txt",)) -> fp.Tree:
    if files is None:
        files = {
            COPIED: 1000, f"{COPIED}.expected": 100,
            SVG: 100,
            SOURCE: 300, GENERATED: 800, SCRIPT: 50,
            "crates/ambre-docx/tests/fixtures/lo/features.expected": 90,
        }
    if sources is None:
        sources = {"crates/ambre-toile/src/tests.rs": 'include_str!("fixtures/rect.svg")'}
    if scripts is None:
        scripts = {SCRIPT: "soffice --convert-to docx features.fodt  # writes features.docx"}
    return fp.Tree(files, sources, scripts, licences)


def refused(third_text: str | None = None, authored_text: str | None = None,
            budgets: str = BUDGETS, planted: fp.Tree | None = None) -> list[str]:
    return fp.breaches(
        third() if third_text is None else third_text,
        authored() if authored_text is None else authored_text,
        budgets,
        tree() if planted is None else planted,
    )[0]


class ACleanTree(unittest.TestCase):
    def test_every_input_with_its_line_passes(self) -> None:
        self.assertEqual(refused(), [])

    def test_the_inputs_are_counted_without_oracles_or_scripts(self) -> None:
        self.assertEqual(fp.breaches(third(), authored(), BUDGETS, tree())[1], 4)

    def test_the_tree_itself_passes(self) -> None:
        third_text, authored_text = fp.read(fp.THIRD_PARTY), fp.read(fp.AUTHORED)
        errors, count = fp.breaches(third_text, authored_text, fp.read(fp.BUDGETS),
                                    fp.scan(third_text, authored_text))
        self.assertEqual(errors, [])
        self.assertGreater(count, 0)


class AMissingLine(unittest.TestCase):
    def test_an_input_with_no_line_fails(self) -> None:
        files = {**tree().files, "crates/ambre-toile/src/fixtures/stray.svg": 10}
        sources = {"crates/ambre-toile/src/tests.rs": "rect.svg stray.svg"}
        errors = refused(planted=tree(files=files, sources=sources))
        self.assertEqual(len(errors), 1)
        self.assertIn("stray.svg: no provenance line", errors[0])

    def test_an_unnamed_script_is_an_input_with_no_line(self) -> None:
        files = {**tree().files, "crates/ambre-toile/src/fixtures/make.sh": 10}
        sources = {"crates/ambre-toile/src/tests.rs": "rect.svg make.sh"}
        errors = refused(planted=tree(files=files, sources=sources))
        self.assertTrue(any("make.sh: no provenance line" in e for e in errors), errors)

    def test_a_file_in_both_registers_fails(self) -> None:
        errors = refused(third_text=third(copied_row(), copied_row(path=SVG)))
        self.assertTrue(any("rect.svg: 2 provenance lines" in e for e in errors), errors)


class ALineWithNoFile(unittest.TestCase):
    def test_a_line_naming_no_file_fails(self) -> None:
        text = third(copied_row(), copied_row(path="crates/ambre-xlsx/tests/fixtures/up/gone.xlsx",
                                              upstream="tests/gone.xlsx"))
        errors = refused(third_text=text)
        self.assertEqual(len(errors), 1)
        self.assertIn("`crates/ambre-xlsx/tests/fixtures/up/gone.xlsx` names no file", errors[0])

    def test_a_line_naming_an_expected_file_fails(self) -> None:
        text = authored(authored_row(SVG), authored_row(SOURCE),
                        authored_row(GENERATED, f"generated by `{SCRIPT}`"),
                        authored_row(f"{COPIED}.expected"))
        errors = refused(authored_text=text)
        self.assertTrue(any("is no input file" in e for e in errors), errors)

    def test_a_row_of_the_wrong_width_fails(self) -> None:
        errors = refused(authored_text=authored() + f"| `{SVG}` | hand-written |\n")
        self.assertTrue(any("2 cells, the table has 3" in e for e in errors), errors)


class TheCap(unittest.TestCase):
    def test_a_file_over_the_cap_fails(self) -> None:
        files = {**tree().files, COPIED: 64 * 1024 + 1}
        errors = refused(planted=tree(files=files))
        self.assertEqual(len(errors), 1)
        self.assertIn("over the cap of 65536", errors[0])

    def test_a_file_at_the_cap_passes(self) -> None:
        self.assertEqual(refused(planted=tree(files={**tree().files, COPIED: 64 * 1024})), [])

    def test_an_expected_file_over_the_cap_fails(self) -> None:
        files = {**tree().files, f"{COPIED}.expected": 70 * 1024}
        self.assertEqual(len(refused(planted=tree(files=files))), 1)

    def test_the_cap_is_read_from_the_budget_row(self) -> None:
        budgets = "| Interop input fixture | 1 KiB each | notes |\n"
        errors = refused(budgets=budgets, planted=tree(files={**tree().files, COPIED: 1025}))
        self.assertEqual(errors, [f"{COPIED}: 1025 octets, over the cap of 1024 (`Interop input fixture`, {fp.BUDGETS})"])

    def test_a_register_with_no_cap_row_fails(self) -> None:
        errors = refused(budgets="| Committed fixture artifact | 256 KB each | notes |\n")
        self.assertEqual(errors, [f"{fp.BUDGETS}: no `Interop input fixture` row with a figure in KiB"])


class ACopiedLine(unittest.TestCase):
    def test_a_short_commit_fails(self) -> None:
        errors = refused(third_text=third(copied_row(commit="57011cf")))
        self.assertTrue(any("no full commit hash" in e for e in errors), errors)

    def test_a_repository_that_is_no_url_fails(self) -> None:
        errors = refused(third_text=third(copied_row(repository="calamine")))
        self.assertTrue(any("no https repository" in e for e in errors), errors)

    def test_an_empty_holder_fails(self) -> None:
        errors = refused(third_text=third(copied_row(holder="")))
        self.assertTrue(any("no copyright holder" in e for e in errors), errors)

    def test_a_licence_the_repository_cannot_carry_fails(self) -> None:
        errors = refused(third_text=third(copied_row(licence="GPL-2.0-only")))
        self.assertTrue(any("`GPL-2.0-only` is not one" in e for e in errors), errors)

    def test_a_missing_licence_text_fails(self) -> None:
        errors = refused(planted=tree(licences=()))
        self.assertEqual(errors, [f"{fp.LICENCES}/calamine.txt: missing, and {fp.THIRD_PARTY} copies from `calamine`"])

    def test_a_licence_text_no_line_names_fails(self) -> None:
        errors = refused(planted=tree(licences=("calamine.txt", "pandoc.txt")))
        self.assertEqual(len(errors), 1)
        self.assertIn("pandoc.txt: no line", errors[0])

    def test_a_companion_licence_text_passes(self) -> None:
        self.assertEqual(refused(planted=tree(licences=("calamine.txt", "calamine-copyright.txt"))), [])


class ABugName(unittest.TestCase):
    def test_names_after_a_tracker_read_as_bugs(self) -> None:
        for stem in ("tdf123456", "bug-1234", "issue_987", "gh-1024", "i54321", "fdo#40000", "883421"):
            self.assertIsNotNone(fp.BUG_NAME.search(stem), stem)

    def test_ordinary_names_pass(self) -> None:
        for stem in ("Comment004", "date_1904", "has_x000D_", "strict-numbering", "table-multiple"):
            self.assertIsNone(fp.BUG_NAME.search(stem), stem)

    def test_an_input_named_after_a_bug_fails(self) -> None:
        bug = "crates/ambre-xlsx/tests/fixtures/up/tdf123456.xlsx"
        files = {**tree().files, bug: 10, f"{bug}.expected": 10}
        text = third(copied_row(), copied_row(path=bug, upstream="tests/fine.xlsx"))
        errors = refused(third_text=text, planted=tree(files=files))
        self.assertEqual(len(errors), 1)
        self.assertIn("tdf123456.xlsx: the name reads as a bug report", errors[0])

    def test_an_upstream_name_after_a_bug_fails(self) -> None:
        errors = refused(third_text=third(copied_row(upstream="sw/qa/extras/data/tdf98765.xlsx")))
        self.assertEqual(len(errors), 1)
        self.assertIn("upstream name `tdf98765`", errors[0])


class AnOracle(unittest.TestCase):
    def test_an_input_nothing_names_fails(self) -> None:
        errors = refused(planted=tree(sources={}))
        self.assertEqual(errors, [f"{SVG}: no oracle, no `.expected` beside it and no test or script names it"])

    def test_a_test_of_another_crate_is_no_oracle(self) -> None:
        sources = {"crates/ambre-prose/src/tests.rs": "rect.svg"}
        self.assertEqual(len(refused(planted=tree(sources=sources))), 1)

    def test_an_expected_file_with_no_input_fails(self) -> None:
        files = {**tree().files, "crates/ambre-xlsx/tests/fixtures/up/gone.expected": 10}
        errors = refused(planted=tree(files=files))
        self.assertEqual(errors, ["crates/ambre-xlsx/tests/fixtures/up/gone.expected: no input file beside it"])

    def test_both_spellings_of_expected_pass(self) -> None:
        files = dict(tree().files)
        files.pop(f"{COPIED}.expected")
        files["crates/ambre-xlsx/tests/fixtures/up/date.expected"] = 10
        self.assertEqual(refused(planted=tree(files=files)), [])


class AnAuthoredLine(unittest.TestCase):
    def test_an_unknown_origin_fails(self) -> None:
        text = authored(authored_row(SVG, origin="found online"), authored_row(SOURCE),
                        authored_row(GENERATED, f"generated by `{SCRIPT}`"))
        errors = refused(authored_text=text)
        self.assertTrue(any("origin `found online`" in e for e in errors), errors)

    def test_an_empty_holds_fails(self) -> None:
        text = authored(authored_row(SVG, holds=""), authored_row(SOURCE),
                        authored_row(GENERATED, f"generated by `{SCRIPT}`"))
        self.assertTrue(any("`Holds` is empty" in e for e in refused(authored_text=text)))

    def test_a_missing_script_fails(self) -> None:
        files = dict(tree().files)
        files.pop(SCRIPT)
        errors = refused(planted=tree(files=files, scripts={}))
        self.assertTrue(any(f"the script `{SCRIPT}` does not exist" in e for e in errors), errors)

    def test_a_script_that_does_not_name_its_file_fails(self) -> None:
        errors = refused(planted=tree(scripts={SCRIPT: "soffice --convert-to docx features.fodt"}))
        self.assertEqual(errors, [f"{fp.AUTHORED}:5: the script `{SCRIPT}` does not name `features.docx`"])


if __name__ == "__main__":
    unittest.main()
