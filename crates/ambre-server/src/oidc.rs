use openidconnect::core::{
    CoreAuthenticationFlow, CoreClient, CoreIdTokenClaims, CoreProviderMetadata,
};
use openidconnect::{
    AuthorizationCode, ClientId, ClientSecret, CsrfToken, EndpointMaybeSet, EndpointNotSet,
    EndpointSet, IssuerUrl, Nonce, PkceCodeChallenge, PkceCodeVerifier, RedirectUrl, Scope,
    TokenResponse,
};
use std::collections::HashMap;
use std::sync::Arc;

use crate::error::AppError;

/// Concrete OIDC client type with all endpoint URLs set from provider discovery.
///
/// `EndpointSet` for `HasAuthUrl` allows `authorize_url()`. `EndpointMaybeSet`
/// for `HasTokenUrl` and `HasUserInfoUrl` covers providers that include token
/// and userinfo endpoints in their .well-known metadata (most do).
pub type OidcClient = CoreClient<
    EndpointSet,
    EndpointNotSet,
    EndpointNotSet,
    EndpointNotSet,
    EndpointMaybeSet,
    EndpointMaybeSet,
>;

/// Per-provider OIDC state: the configured client and its redirect URI.
///
/// The redirect URI is stored separately from the client. The same
/// `OidcClient` can then be used by `login_url` and `exchange_code`,
/// without baking the URI into the typestate at construction time.
pub struct OidcProviderState {
    pub client: OidcClient,
    pub redirect_uri: RedirectUrl,
    /// Shared HTTP client for token exchange. `reqwest::Client` owns a
    /// connection pool internally and is cheap to clone. One instance is
    /// built at discovery time and reused for every callback, rather than
    /// spinning up a fresh pool (and TLS handshake) per request.
    pub http_client: reqwest::Client,
}

/// Map of each configured OIDC provider to its state. A provider absent from
/// it is not configured.
///
/// Wrapped in `Arc` so every Axum handler can reference the same
/// discovered clients without cloning the entire map.
pub type OidcClients = Arc<HashMap<ambre_core::OidcProvider, OidcProviderState>>;

/// Returned by `GET /auth/{provider}/login`.
///
/// The client redirects the browser to `url` which begins the
/// authorization code flow at the OIDC provider.
#[derive(serde::Serialize)]
pub struct LoginResponse {
    pub url: String,
    pub state: ambre_core::OidcState,
}

/// Received by `POST /auth/{provider}/callback`.
///
/// The client sends the authorization `code` and the `state` (CSRF token)
/// returned by the login endpoint. The server validates the state against
/// Redis, exchanges the code for tokens, and creates a session.
#[derive(serde::Deserialize)]
pub struct CallbackRequest {
    pub code: ambre_core::OidcCode,
    pub state: ambre_core::OidcState,
}

/// Returned by `POST /auth/{provider}/callback` after successful authentication.
#[derive(serde::Serialize)]
pub struct CallbackResponse {
    #[serde(with = "ambre_core::serde_id::user_id")]
    pub user_id: ambre_core::UserId,
    pub email: ambre_core::Email,
    pub display_name: ambre_core::DisplayName,
    /// True when the user row was just created (no master key yet).
    /// The client should prompt the user to set up their master key.
    pub is_new_user: bool,
    /// Access JWT, kept in client memory and sent as `Authorization: Bearer`.
    pub access_token: ambre_protocol::ws::AccessToken,
    /// Opaque refresh token, exchanged at `/auth/refresh` for a new access JWT.
    pub refresh_token: ambre_protocol::ws::RefreshToken,
    /// Access-token lifetime in seconds, so the client can schedule a refresh.
    pub access_expires_in: ambre_core::Seconds,
}

/// A secret of the OIDC exchange: the client secret the provider issued, or
/// a PKCE verifier. `Debug` prints no byte of it, so a logged `Config` or
/// sign-in state carries none.
#[derive(Clone, Default, PartialEq, Eq)]
pub struct OidcSecret(String);

impl OidcSecret {
    /// Wraps the secret text.
    pub fn new(secret: String) -> Self {
        Self(secret)
    }

    /// The secret text, for the one call that presents it.
    pub fn expose(&self) -> &str {
        &self.0
    }
}

impl std::fmt::Debug for OidcSecret {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("OidcSecret(<redacted>)")
    }
}

/// Transient OIDC authorization state stored in Redis (TTL 10 min).
///
/// The PKCE verifier and nonce are generated by `login_url` and must
/// be presented again during token exchange to prevent authorization
/// code interception.
pub struct OidcAuthState {
    pub pkce_verifier_secret: OidcSecret,
    pub nonce: Nonce,
}

/// The issuer the `google` provider is discovered at.
pub const GOOGLE_ISSUER: &str = "https://accounts.google.com";

/// The provider clients the relay starts with. An empty client id means
/// provider sign-in is off, and nothing is discovered. A configured provider
/// that does not answer is an error, so the start stops (`SRV-074`).
pub async fn start_oidc_clients(
    google_issuer: &str,
    google_client_id: &str,
    google_client_secret: &OidcSecret,
    google_redirect_uri: &str,
) -> Result<OidcClients, AppError> {
    if google_client_id.is_empty() {
        return Ok(Arc::new(HashMap::new()));
    }
    init_oidc_clients(
        google_issuer,
        google_client_id,
        google_client_secret,
        google_redirect_uri,
    )
    .await
}

/// Discovers the `google` provider's metadata at `google_issuer` and
/// initializes an `OidcClient`.
///
/// The resulting `OidcClients` map is stored in `AppState` and used by
/// the `/auth/{provider}/login` and `/auth/{provider}/callback` routes.
async fn init_oidc_clients(
    google_issuer: &str,
    google_client_id: &str,
    google_client_secret: &OidcSecret,
    google_redirect_uri: &str,
) -> Result<OidcClients, AppError> {
    let http_client = reqwest::Client::new();

    let google_issuer = IssuerUrl::new(google_issuer.to_string())
        .map_err(|e| AppError::Oidc(format!("invalid google issuer URL: {e}")))?;

    let provider_metadata = CoreProviderMetadata::discover_async(google_issuer, &http_client)
        .await
        .map_err(|e| AppError::Oidc(format!("google discovery failed: {e}")))?;

    let redirect_uri = RedirectUrl::new(google_redirect_uri.to_string())
        .map_err(|e| AppError::Oidc(format!("invalid redirect URI: {e}")))?;

    let client = OidcClient::from_provider_metadata(
        provider_metadata,
        ClientId::new(google_client_id.to_string()),
        Some(ClientSecret::new(google_client_secret.expose().to_owned())),
    );

    let mut map = HashMap::new();
    map.insert(
        ambre_core::OidcProvider::Google,
        OidcProviderState {
            client,
            redirect_uri,
            http_client,
        },
    );

    Ok(Arc::new(map))
}

/// Generates an OIDC authorization URL with PKCE challenge, CSRF token, and nonce.
///
/// Returns the URL the client must redirect to, and the `OidcAuthState` that must
/// be stored in Redis (keyed by the CSRF token). The callback needs it to validate
/// the PKCE verifier and nonce.
pub async fn login_url(
    state: &OidcProviderState,
) -> Result<(LoginResponse, OidcAuthState), AppError> {
    let (pkce_challenge, pkce_verifier) = PkceCodeChallenge::new_random_sha256();

    let client_with_redirect = state
        .client
        .clone()
        .set_redirect_uri(state.redirect_uri.clone());

    let (auth_url, csrf_state, nonce) = client_with_redirect
        .authorize_url(
            CoreAuthenticationFlow::AuthorizationCode,
            CsrfToken::new_random,
            Nonce::new_random,
        )
        .add_scope(Scope::new("openid".to_string()))
        .add_scope(Scope::new("email".to_string()))
        .add_scope(Scope::new("profile".to_string()))
        .set_pkce_challenge(pkce_challenge)
        .url();

    let csrf_secret = csrf_state.secret().clone();
    let verifier_secret = pkce_verifier.secret().clone();

    let oidc_state = OidcAuthState {
        pkce_verifier_secret: OidcSecret::new(verifier_secret),
        nonce,
    };

    Ok((
        LoginResponse {
            url: auth_url.to_string(),
            state: ambre_core::OidcState::new(csrf_secret),
        },
        oidc_state,
    ))
}

/// Exchanges an authorization code for tokens, validates the ID token, and returns the claims.
///
/// Uses the PKCE verifier and nonce from the `OidcAuthState` (retrieved from Redis)
/// to prevent code interception. The ID token is verified against the provider's JWKS keys.
pub async fn exchange_code(
    provider: &OidcProviderState,
    code: String,
    stored_state: &OidcAuthState,
) -> Result<CoreIdTokenClaims, AppError> {
    let auth_code = AuthorizationCode::new(code);
    let pkce_verifier =
        PkceCodeVerifier::new(stored_state.pkce_verifier_secret.expose().to_owned());

    let http_client = &provider.http_client;
    let client_with_redirect = provider
        .client
        .clone()
        .set_redirect_uri(provider.redirect_uri.clone());

    let exchange_client = client_with_redirect.clone();
    let exchange_req = exchange_client
        .exchange_code(auth_code)
        .map_err(|e| AppError::Oidc(format!("exchange_code setup failed: {e}")))?;

    let token_response = exchange_req
        .set_pkce_verifier(pkce_verifier)
        .request_async(http_client)
        .await
        .map_err(|e| AppError::Oidc(format!("token exchange failed: {e}")))?;

    let id_token = token_response
        .id_token()
        .ok_or_else(|| AppError::Oidc("no id_token in response".into()))?;

    let claims = id_token
        .clone()
        .into_claims(
            &client_with_redirect.id_token_verifier(),
            &stored_state.nonce,
        )
        .map_err(|e| AppError::Oidc(format!("id token verification failed: {e}")))?;

    Ok(claims)
}

/// An identity provider that a test runs in process. It publishes its
/// discovery document and its key. It hands out a code for an authorization
/// URL, and answers the code with an identity token it signs.
#[cfg(test)]
pub(crate) mod stub {
    use std::sync::{Arc, Mutex};

    use openidconnect::core::{
        CoreIdToken, CoreIdTokenClaims, CoreJwsSigningAlgorithm, CoreRsaPrivateSigningKey,
    };
    use openidconnect::{
        Audience, EmptyAdditionalClaims, EndUserEmail, EndUserName, IssuerUrl, JsonWebKeyId, Nonce,
        PkceCodeChallenge, PkceCodeVerifier, PrivateSigningKey, StandardClaims, SubjectIdentifier,
    };
    use rsa::pkcs1::EncodeRsaPrivateKey;

    /// The client the provider knows.
    pub(crate) const CLIENT_ID: &str = "client";
    /// The subject, the email and the name of the person who signs in.
    pub(crate) const SUBJECT: &str = "stub-subject";
    pub(crate) const EMAIL: &str = "ada@example.org";
    pub(crate) const NAME: &str = "Ada";

    /// What one authorization left for the token endpoint to check.
    struct Grant {
        code: String,
        challenge: String,
        nonce: String,
    }

    struct Shared {
        issuer: String,
        key: CoreRsaPrivateSigningKey,
        /// A key the provider does not publish, signing in place of `key`
        /// while `forge` is set.
        foreign: CoreRsaPrivateSigningKey,
        forge: bool,
        grant: Option<Grant>,
    }

    /// A running provider. Its address is its issuer.
    #[derive(Clone)]
    pub(crate) struct StubProvider {
        pub(crate) issuer: String,
        shared: Arc<Mutex<Shared>>,
    }

    fn signing_key(kid: &str) -> CoreRsaPrivateSigningKey {
        let key = rsa::RsaPrivateKey::new(&mut rsa::rand_core::OsRng, 2048).unwrap();
        let pem = key.to_pkcs1_pem(rsa::pkcs8::LineEnding::LF).unwrap();
        CoreRsaPrivateSigningKey::from_pem(&pem, Some(JsonWebKeyId::new(kid.into()))).unwrap()
    }

    impl StubProvider {
        pub(crate) async fn spawn() -> Self {
            let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
            let issuer = format!("http://{}", listener.local_addr().unwrap());
            let stub = Self {
                issuer: issuer.clone(),
                shared: Arc::new(Mutex::new(Shared {
                    issuer: issuer.clone(),
                    // The same key id on both, so only the signature tells them apart.
                    key: signing_key("k"),
                    foreign: signing_key("k"),
                    forge: false,
                    grant: None,
                })),
            };
            let metadata = serde_json::json!({
                "issuer": issuer,
                "authorization_endpoint": format!("{issuer}/authorize"),
                "token_endpoint": format!("{issuer}/token"),
                "jwks_uri": format!("{issuer}/jwks"),
                "response_types_supported": ["code"],
                "subject_types_supported": ["public"],
                "id_token_signing_alg_values_supported": ["RS256"],
            });
            let jwks = {
                let shared = stub.shared.lock().unwrap();
                serde_json::json!({ "keys": [shared.key.as_verification_key()] })
            };
            let shared = Arc::clone(&stub.shared);
            let app = axum::Router::new()
                .route(
                    "/.well-known/openid-configuration",
                    axum::routing::get(move || async move { axum::Json(metadata) }),
                )
                .route(
                    "/jwks",
                    axum::routing::get(move || async move { axum::Json(jwks) }),
                )
                .route(
                    "/token",
                    axum::routing::post(
                        move |axum::extract::Form(form): axum::extract::Form<
                            std::collections::HashMap<String, String>,
                        >| async move { token(&shared, &form) },
                    ),
                );
            tokio::spawn(async move { axum::serve(listener, app).await });
            stub
        }

        /// Signs every later identity token with a key the provider does not
        /// publish.
        pub(crate) fn forge(&self) {
            self.shared.lock().unwrap().forge = true;
        }

        /// What the provider does once the person signs in at `url`. It keeps
        /// the challenge and the one-time value the URL carries. It returns the
        /// code it hands back.
        pub(crate) fn authorize(&self, url: &str) -> String {
            let url = url::Url::parse(url).unwrap();
            let param = |name: &str| {
                url.query_pairs()
                    .find(|(k, _)| k == name)
                    .map(|(_, v)| v.into_owned())
                    .unwrap()
            };
            let code = format!("code-{}", uuid::Uuid::new_v4());
            self.shared.lock().unwrap().grant = Some(Grant {
                code: code.clone(),
                challenge: param("code_challenge"),
                nonce: param("nonce"),
            });
            code
        }
    }

    /// The token endpoint: the code it handed out, under the verifier whose
    /// challenge the authorization carried, answers with a signed identity
    /// token. Anything else is refused.
    fn token(
        shared: &Mutex<Shared>,
        form: &std::collections::HashMap<String, String>,
    ) -> axum::response::Response {
        use axum::response::IntoResponse;
        let mut shared = shared.lock().unwrap();
        let Some(grant) = shared.grant.take() else {
            return refused();
        };
        let verifier =
            PkceCodeVerifier::new(form.get("code_verifier").cloned().unwrap_or_default());
        let challenge = PkceCodeChallenge::from_code_verifier_sha256(&verifier);
        if form.get("code") != Some(&grant.code) || challenge.as_str() != grant.challenge {
            return refused();
        }
        let now = chrono::Utc::now();
        let claims = CoreIdTokenClaims::new(
            IssuerUrl::new(shared.issuer.clone()).unwrap(),
            vec![Audience::new(CLIENT_ID.into())],
            now + chrono::Duration::minutes(5),
            now,
            StandardClaims::new(SubjectIdentifier::new(SUBJECT.into()))
                .set_email(Some(EndUserEmail::new(EMAIL.into())))
                .set_email_verified(Some(true))
                .set_name(Some(EndUserName::new(NAME.into()).into())),
            EmptyAdditionalClaims {},
        )
        .set_nonce(Some(Nonce::new(grant.nonce)));
        let key = if shared.forge {
            &shared.foreign
        } else {
            &shared.key
        };
        let id_token = CoreIdToken::new(
            claims,
            key,
            CoreJwsSigningAlgorithm::RsaSsaPkcs1V15Sha256,
            None,
            None,
        )
        .unwrap();
        axum::Json(serde_json::json!({
            "access_token": "stub-access",
            "token_type": "bearer",
            "id_token": id_token.to_string(),
        }))
        .into_response()
    }

    fn refused() -> axum::response::Response {
        use axum::response::IntoResponse;
        (
            axum::http::StatusCode::BAD_REQUEST,
            axum::Json(serde_json::json!({ "error": "invalid_grant" })),
        )
            .into_response()
    }
}

#[cfg(test)]
mod tests {
    use super::stub::{CLIENT_ID, EMAIL, SUBJECT, StubProvider};
    use super::*;

    /// An issuer nothing listens on.
    const SILENT_ISSUER: &str = "http://127.0.0.1:1";

    /// A provider that publishes its discovery document and its key. Returns
    /// its issuer.
    async fn spawn_provider() -> String {
        StubProvider::spawn().await.issuer
    }

    /// The client secret every test configures.
    fn secret() -> OidcSecret {
        OidcSecret::new("secret".to_owned())
    }

    /// The `google` client discovered at `stub`.
    async fn client_of(stub: &StubProvider) -> OidcClients {
        start_oidc_clients(&stub.issuer, CLIENT_ID, &secret(), "https://app/cb")
            .await
            .unwrap()
    }

    /// `SRV-022`: the code the provider hands back is exchanged under the
    /// verifier the sign-in kept. The relay checks the identity token's
    /// signature, issuer, audience and one-time value.
    #[tokio::test]
    async fn a_provider_code_is_exchanged_for_a_verified_identity() {
        let stub = StubProvider::spawn().await;
        let clients = client_of(&stub).await;
        let (login, kept) = login_url(&clients[&ambre_core::OidcProvider::Google])
            .await
            .unwrap();
        let code = stub.authorize(&login.url);
        let claims = exchange_code(&clients[&ambre_core::OidcProvider::Google], code, &kept)
            .await
            .unwrap();
        assert_eq!(claims.subject().as_str(), SUBJECT);
        assert_eq!(claims.email().map(|e| e.as_str()), Some(EMAIL));
        assert_eq!(claims.email_verified(), Some(true));
    }

    /// `SRV-022`: an exchange is refused in three cases. The token is signed by
    /// a key the provider does not publish. Its one-time value is not the one
    /// the sign-in kept. The verifier is not the sign-in's.
    #[tokio::test]
    async fn an_identity_the_relay_cannot_verify_is_refused() {
        let stub = StubProvider::spawn().await;
        let clients = client_of(&stub).await;
        let provider = &clients[&ambre_core::OidcProvider::Google];
        let refused_at = |result: Result<CoreIdTokenClaims, AppError>, stage: &str| match result {
            Err(AppError::Oidc(reason)) => assert!(reason.starts_with(stage), "{reason}"),
            Err(other) => panic!("{other}"),
            Ok(_) => panic!("the exchange was accepted"),
        };

        let (login, kept) = login_url(provider).await.unwrap();
        let other_nonce = OidcAuthState {
            pkce_verifier_secret: kept.pkce_verifier_secret.clone(),
            nonce: Nonce::new("another".into()),
        };
        let code = stub.authorize(&login.url);
        refused_at(
            exchange_code(provider, code, &other_nonce).await,
            "id token verification failed",
        );

        let (login, kept) = login_url(provider).await.unwrap();
        let other_verifier = OidcAuthState {
            pkce_verifier_secret: OidcSecret::new(
                "a-verifier-the-sign-in-never-made-0123456789".into(),
            ),
            nonce: kept.nonce.clone(),
        };
        let code = stub.authorize(&login.url);
        refused_at(
            exchange_code(provider, code, &other_verifier).await,
            "token exchange failed",
        );

        stub.forge();
        let (login, kept) = login_url(provider).await.unwrap();
        let code = stub.authorize(&login.url);
        refused_at(
            exchange_code(provider, code, &kept).await,
            "id token verification failed",
        );
    }

    /// `SRV-074`: a configured provider that does not answer stops the start.
    /// With no client id configured nothing is discovered, and sign-in is off.
    #[tokio::test]
    async fn a_configured_provider_that_does_not_answer_stops_the_start() {
        let started =
            start_oidc_clients(SILENT_ISSUER, "client", &secret(), "https://app/cb").await;
        assert!(matches!(started, Err(AppError::Oidc(_))));
        let off = start_oidc_clients(SILENT_ISSUER, "", &OidcSecret::default(), "")
            .await
            .unwrap();
        assert!(off.is_empty());
    }

    /// `SRV-172`: a sign-in with a configured provider is sent to that
    /// provider's authorization endpoint, under the configured client.
    #[tokio::test]
    async fn a_sign_in_is_sent_to_the_configured_provider() {
        let issuer = spawn_provider().await;
        let clients = start_oidc_clients(&issuer, "client", &secret(), "https://app/cb")
            .await
            .unwrap();
        let (login, _) = login_url(&clients[&ambre_core::OidcProvider::Google])
            .await
            .unwrap();
        assert!(
            login.url.starts_with(&format!("{issuer}/authorize?")),
            "{}",
            login.url
        );
        assert!(login.url.contains("client_id=client"), "{}", login.url);
    }
}
